export function getMoveContext(moveName: string): MoveContext {
  const move = MOVE_LIBRARY[moveName];

  if (!move) {
    throw new Error(`Unknown Battle Dinos move: ${moveName}`);
  }

  return move;
}

export function hasMoveContext(moveName: string): boolean {
  return moveName in MOVE_LIBRARY;
}